"""
Resume file storage on Supabase Storage.

Render's disk is wiped on every deploy, so a PDF forged on the server
disappeared the next time code shipped — and a resume forged locally stored a
Windows path the deployed app could never serve. Files now go to a private
Supabase Storage bucket as well as local disk, and are served through
short-lived signed URLs.

Uses the service-role key server-side only (never shipped to the PWA). When
SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY aren't set, everything degrades to
local disk only, and enabled() reports False (surfaced as storage: off on
/health).
"""

from __future__ import annotations

import os
import re
import time
from typing import Optional

import requests

BUCKET = "resumes"
_TIMEOUT = 20
_bucket_ready = False
_last_ping = 0.0

# Filenames are generated by the forge (slug + date + extension); anything
# else is refused so a request can never address another bucket path.
_SAFE_NAME = re.compile(r"^[A-Za-z0-9_-]+\.(pdf|json)$")  # e.g. pwc_role_2026-11-24.pdf


def _base() -> str:
    return (os.environ.get("SUPABASE_URL") or "").rstrip("/") + "/storage/v1"


def _headers(extra: Optional[dict] = None) -> dict:
    key = os.environ.get("SUPABASE_SERVICE_ROLE_KEY") or ""
    h = {"Authorization": f"Bearer {key}", "apikey": key}
    if extra:
        h.update(extra)
    return h


def enabled() -> bool:
    return bool(os.environ.get("SUPABASE_URL") and os.environ.get("SUPABASE_SERVICE_ROLE_KEY"))


def safe_name(name: str) -> bool:
    return bool(_SAFE_NAME.match(name or ""))


def ensure_bucket() -> bool:
    """Create the private bucket if it doesn't exist. Idempotent, cached."""
    global _bucket_ready
    if _bucket_ready or not enabled():
        return _bucket_ready
    r = requests.get(f"{_base()}/bucket/{BUCKET}", headers=_headers(), timeout=_TIMEOUT)
    if r.status_code == 200:
        _bucket_ready = True
        return True
    r = requests.post(f"{_base()}/bucket", headers=_headers(),
                      json={"id": BUCKET, "name": BUCKET, "public": False}, timeout=_TIMEOUT)
    # 409/400 "already exists" from a concurrent create is fine too.
    _bucket_ready = r.status_code in (200, 201) or "exist" in r.text.lower()
    return _bucket_ready


def upload(name: str, data: bytes, content_type: str) -> bool:
    if not enabled() or not safe_name(name) or not ensure_bucket():
        return False
    r = requests.post(f"{_base()}/object/{BUCKET}/{name}", data=data, timeout=_TIMEOUT,
                      headers=_headers({"Content-Type": content_type, "x-upsert": "true"}))
    return r.status_code in (200, 201)


def download(name: str) -> Optional[bytes]:
    if not enabled() or not safe_name(name):
        return None
    r = requests.get(f"{_base()}/object/{BUCKET}/{name}", headers=_headers(), timeout=_TIMEOUT)
    return r.content if r.status_code == 200 else None


def signed_url(name: str, expires_in: int = 600) -> Optional[str]:
    if not enabled() or not safe_name(name):
        return None
    r = requests.post(f"{_base()}/object/sign/{BUCKET}/{name}", headers=_headers(),
                      json={"expiresIn": expires_in}, timeout=_TIMEOUT)
    if r.status_code != 200:
        return None
    path = r.json().get("signedURL") or r.json().get("signedUrl")
    return f"{_base()}{path}" if path else None


def ping(min_interval_s: int = 6 * 3600) -> str:
    """Touch the Storage API at most every `min_interval_s`. Called from /health:
    a Supabase *API* request is unambiguous project activity, in case direct
    Postgres queries alone don't count toward the free tier's 7-day idle pause.
    Returns "ok", "off", or "error"."""
    global _last_ping
    if not enabled():
        return "off"
    if time.time() - _last_ping < min_interval_s:
        return "ok"
    try:
        ok = ensure_bucket() and requests.get(
            f"{_base()}/bucket/{BUCKET}", headers=_headers(), timeout=_TIMEOUT).status_code == 200
    except requests.RequestException:
        ok = False
    if ok:
        _last_ping = time.time()
    return "ok" if ok else "error"


def backfill(directory: str) -> dict:
    """Upload every resume PDF/JSON in `directory` (e.g. an old local
    shared/resumes) that isn't in the bucket yet. Safe to re-run."""
    from pathlib import Path
    done, skipped = [], []
    for p in sorted(Path(directory).iterdir()):
        if not safe_name(p.name):
            skipped.append(p.name)
            continue
        ctype = "application/pdf" if p.suffix == ".pdf" else "application/json"
        (done if upload(p.name, p.read_bytes(), ctype) else skipped).append(p.name)
    return {"uploaded": done, "skipped": skipped}


if __name__ == "__main__":
    # python -m core.storage <dir>   — one-off backfill of existing resumes
    import json
    import sys
    from dotenv import load_dotenv
    load_dotenv()
    print(json.dumps(backfill(sys.argv[1] if len(sys.argv) > 1 else "shared/resumes"), indent=2))
